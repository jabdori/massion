#!/usr/bin/env node
import {readFile,writeFile} from 'node:fs/promises';

const root=new URL('../',import.meta.url),output=new URL('src/ui-tokens.ts',root);
const visual=JSON.parse(await readFile(new URL('docs/product/screens/visual.json',root),'utf8'));
const name=value=>value.replaceAll('.','-').replaceAll('_','-');
const declaration=(key,value)=>` --${key}:${value};`;
const px=value=>`${value}px`;

function palette(theme){
 const colors=visual.palettes[theme],lines=[` color-scheme:${theme};`];
 for(const [key,value] of Object.entries(colors))lines.push(declaration('palette-'+key,value));
 for(const [role,reference] of Object.entries(visual.tokens)){
  const value=colors[reference.replace(/^--palette-/,'')];
  if(!value)throw Error(`Missing ${theme} palette value for ${role}`);
  // Emit concrete role values: the contract runner reads root custom properties directly.
  lines.push(declaration(role.slice(2),value));
 }
 return lines;
}

const measurements=[];
const add=(key,value)=>measurements.push(declaration(key,value));
for(const [region,values] of Object.entries(visual.shell))for(const [key,value] of Object.entries(values)){
 if(typeof value!=='number')continue;
 add(region+'-'+name(key),key.endsWith('ratio')?String(value):px(value));
}
add('conversation-max-width',px(visual.shell.conversation.column_max_width));
add('conversation-min-width',px(visual.shell.pane.conversation_min_width));
for(const [role,values] of Object.entries(visual.typography)){
 for(const [key,suffix] of [['fs','size'],['fw','weight'],['lh','line-height'],['ff','family']]){
  add('type-'+name(role)+'-'+suffix,values[key]);
 }
}
for(const [component,values] of Object.entries(visual.components)){
 for(const [key,suffix] of [['radius','radius'],['pad','padding'],['fs','font-size'],['fw','font-weight'],['lh','line-height'],['bd','border'],['focus_ring','focus-width'],['shadow','shadow']]){
  if(values[key]!=null)add(name(component)+'-'+suffix,values[key]);
 }
 for(const key of ['height','editor_max_height'])if(typeof values[key]==='number')add(name(component)+'-'+name(key),px(values[key]));
}
const spaces=new Set([0,...Object.keys(visual.rhythm.conversation_gaps_seen).map(Number)]);
for(const values of Object.values(visual.components))for(const match of (values.pad||'').matchAll(/(\d+)px/g))spaces.add(Number(match[1]));
for(const space of [...spaces].sort((a,b)=>a-b))add('space-'+space,px(space));
add('conversation-gap',px(visual.rhythm.conversation_gap_px_mode));
for(const key of ['fast','slow','ease'])add('motion-'+key,visual.motion[key]);
add('focus-width',visual.components.composer.focus_ring);
add('focus-ring','var(--fg-4)');

// Preserve existing values where visual.json has no measurement; provenance is emitted with the artifact.
add('focus-offset','4px');
add('font-sans',visual.typography['composer.textbox'].ff+',Pretendard,Inter,ui-sans-serif,system-ui,-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif');
add('font-mono','ui-monospace,SFMono-Regular,Menlo,monospace');
add('overlay-color','#000a');
add('shadow-color','#0008');
for(const [alias,role] of Object.entries({ink:'fg',muted:'fg-3',green:'fg',soft:'bg-3',warn:'fg-2','warn-bg':'bg-2'}))add(alias,`var(--${role})`);

const source=`// Generated by scripts/generate-ui-tokens.mjs; do not edit.
// Source: docs/product/screens/visual.json (role palettes, shell, typography, components, rhythm, motion).
// Palette and motion evidence: visual.json.evidence; no prototype files are copied or required at generation time.
// Fallback provenance: values absent from visual.json are preserved from existing UI styles:
// - src/workbench.ts :root font-family supplies the sans fallback stack; control outline-offset supplies 4px.
// - src/results-panel.ts pre.result-doc supplies the existing monospace stack (also apps/settings panels).
// - src/members-panel.ts .member-dialog and .member-box supply overlay #000a and shadow #0008, in both themes.
// - Legacy aliases preserve src/workbench.ts role mappings; green remains neutral per visual.json.rules.
// Visual-gate correction: focus uses visual.json muted foreground role fg-4; width remains components.composer.focus_ring.
export const uiTokensStyle=String.raw\`:root{
${[...palette('light'),...measurements].join('\n')}
}
@media (prefers-color-scheme: dark){
 :root{
${palette('dark').join('\n')}
 }
}
@media (prefers-reduced-motion: reduce){
 :root{
${['fast','slow'].map(key=>declaration('motion-'+key,visual.motion.reduced_motion)).join('\n')}
 }
}
\`;
`;

const args=process.argv.slice(2);
if(args.length>1||args.some(arg=>!['--stdout','--check'].includes(arg)))throw Error('Usage: node scripts/generate-ui-tokens.mjs [--stdout|--check]');
if(args[0]==='--stdout')process.stdout.write(source);
else if(args[0]==='--check'){
 const checkedIn=await readFile(output,'utf8');
 if(checkedIn!==source)throw Error('UI tokens are out of date; run node scripts/generate-ui-tokens.mjs');
}else await writeFile(output,source);
